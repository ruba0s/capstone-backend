"""Audit the cleaned datasets in data/processed/ and write reports/dataset_audit.md.

For each dataset: does it have chronological age, how many participants, the age
range, missing values, and units. It also shows how many people appear in more than
one dataset and whether the age ranges overlap, which decides how the models can be
combined.

Run from the repo root:  python audit_datasets.py
"""
from itertools import combinations
from pathlib import Path

import pandas as pd

BASE = Path(__file__).resolve().parent
PROCESSED = BASE / "data" / "processed"
REPORT = BASE / "reports" / "dataset_audit.md"

ID_COL = "SEQN"
AGE_CANDIDATES = ["RIDAGEYR", "age"]
NON_FEATURES = {ID_COL, "RIDAGEYR", "age", "age_group"}

# Edit the file names here if a teammate saves a dataset under a different name.
DATASETS = {
    "biomarker": PROCESSED / "biomarker_data.csv",
    "activity": PROCESSED / "activity_final.csv",
    "sleep": PROCESSED / "sleep_data.csv",
}

# Units from the NHANES 2013-2014 documentation plus our own feature definitions.
# Add new feature columns here so they do not show up as "unknown".
UNITS = {
    "RIAGENDR": "code (1 = male, 2 = female)",
    "PAQ605": "code (1 = yes, 2 = no)",
    "BMXBMI": "kg/m^2",
    "LBXGLU": "mg/dL",
    "DIQ010": "code (1 = yes, 2 = no, 3 = borderline)",
    "LBXGLT": "mg/dL",
    "LBXIN": "uU/mL",
    "avg_daily_activity": "MIMS units per valid minute",
    "activity_variability": "MIMS units (std of daily activity)",
    "avg_active_minutes": "minutes per day",
    "sleep_hours": "hours per night, usual weekday (12 = 12 or more)",
}


def find_age_col(df):
    for col in AGE_CANDIDATES:
        if col in df.columns:
            return col
    return None


def audit_one(name, path):
    info = {"name": name, "path": path, "found": path.exists()}
    if not info["found"]:
        return info

    df = pd.read_csv(path)
    info["rows"] = len(df)

    # Participants
    if ID_COL in df.columns:
        ids = df[ID_COL].dropna().astype(int)
        info["ids"] = set(ids)
        info["participants"] = len(info["ids"])
        info["duplicate_ids"] = int(ids.duplicated().sum())
    else:
        info["ids"] = None
        info["participants"] = len(df)
        info["duplicate_ids"] = None

    # Age
    age_col = find_age_col(df)
    info["age_col"] = age_col
    age = pd.to_numeric(df[age_col], errors="coerce").dropna() if age_col else pd.Series(dtype=float)
    info["has_age"] = len(age) > 0
    if info["has_age"]:
        info["age_min"] = float(age.min())
        info["age_max"] = float(age.max())
        info["age_median"] = float(age.median())
        info["under18"] = float((age < 18).mean())
        info["over65"] = float((age >= 65).mean())

    # Missing values and features
    missing = df.isna().sum()
    info["missing_cells"] = int(missing.sum())
    info["missing_by_col"] = {c: int(n) for c, n in missing.items() if n > 0}
    info["features"] = [c for c in df.columns if c not in NON_FEATURES]
    return info


def age_text(info):
    return "%d to %d" % (round(info["age_min"]), round(info["age_max"]))


def build_report(infos):
    lines = ["# Dataset audit", ""]
    lines.append("Generated by `audit_datasets.py` from the cleaned files in `data/processed/`.")
    lines.append("")

    # Summary table
    lines.append("| Dataset | Has age | Participants | Age range | Missing cells | Features |")
    lines.append("|---|---|---|---|---|---|")
    for d in infos:
        if not d["found"]:
            lines.append("| %s | file not found | - | - | - | - |" % d["name"])
            continue
        has_age = "yes (%s)" % d["age_col"] if d["has_age"] else "NO"
        rng = age_text(d) if d["has_age"] else "-"
        lines.append("| %s | %s | %d | %s | %d | %d |" % (
            d["name"], has_age, d["participants"], rng, d["missing_cells"], len(d["features"])))
    lines.append("")

    # Details per dataset
    for d in infos:
        if not d["found"]:
            lines.append("## %s" % d["name"])
            lines.append("Not found at `%s`. Not audited yet." % d["path"].relative_to(BASE))
            lines.append("")
            continue
        lines.append("## %s" % d["name"])
        lines.append("- Rows: %d. Participants (unique %s): %d." % (d["rows"], ID_COL, d["participants"]))
        if d["duplicate_ids"]:
            lines.append("- WARNING: %d duplicate participant IDs." % d["duplicate_ids"])
        if d["ids"] is None:
            lines.append("- WARNING: no %s column, so participants could not be matched across datasets." % ID_COL)
        if d["has_age"]:
            lines.append("- Age: median %.0f, under 18: %.0f%%, 65 and over: %.0f%%." % (
                d["age_median"], d["under18"] * 100, d["over65"] * 100))
        else:
            lines.append("- No chronological age column, so this dataset cannot be used to train an age model.")
        if d["missing_by_col"]:
            parts = ["%s (%d)" % (c, n) for c, n in d["missing_by_col"].items()]
            lines.append("- Missing values: " + ", ".join(parts) + ".")
        else:
            lines.append("- Missing values: none.")
        lines.append("- Units:")
        for col in d["features"]:
            lines.append("  - `%s`: %s" % (col, UNITS.get(col, "unknown, add to UNITS")))
        lines.append("")

    # Overlap
    present = [d for d in infos if d["found"]]
    with_ids = [d for d in present if d["ids"]]
    lines.append("## Overlap between datasets")
    if len(with_ids) >= 2:
        for a, b in combinations(with_ids, 2):
            lines.append("- %s and %s share %d participants." % (a["name"], b["name"], len(a["ids"] & b["ids"])))
        shared_all = set.intersection(*[d["ids"] for d in with_ids])
        lines.append("- All %d datasets share %d participants." % (len(with_ids), len(shared_all)))
    else:
        lines.append("- Need at least two datasets with a %s column to compare." % ID_COL)
    aged = [d for d in present if d["has_age"]]
    if len(aged) >= 2:
        lo = max(d["age_min"] for d in aged)
        hi = min(d["age_max"] for d in aged)
        if lo <= hi:
            lines.append("- Age range that every dataset covers: %d to %d." % (round(lo), round(hi)))
        else:
            lines.append("- The age ranges do not overlap.")
    under = [d["name"] for d in aged if d["under18"] > 0]
    if under and len(under) < len(aged):
        lines.append("- Includes participants under 18: %s. The others are adults only." % ", ".join(under))
    lines.append("")
    return "\n".join(lines)


def main():
    infos = [audit_one(name, path) for name, path in DATASETS.items()]
    report = build_report(infos)
    print(report)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report)
    print("Saved to %s" % REPORT.relative_to(BASE))


if __name__ == "__main__":
    main()
